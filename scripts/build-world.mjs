// Builds data/world-maps.js from Natural Earth 50m admin-0 countries (public domain), passed as --ne <file>.
// Two windows: `evidence` (where the ten appraised studies were run) and `horn` (the six countries in Foini et al.).
import { readFile, writeFile } from 'node:fs/promises'

const arg = name => { const i = process.argv.indexOf(`--${name}`); return i > 0 ? process.argv[i + 1] : undefined }
const geo = JSON.parse(await readFile(arg('ne'), 'utf8'))
const polys = g => g.type === 'Polygon' ? [g.coordinates] : g.coordinates
const area = ring => Math.abs(ring.reduce((s, p, i) => { const q = ring[(i + 1) % ring.length]; return s + p[0] * q[1] - q[0] * p[1] }, 0)) / 2
const f1 = n => String(Math.round(n * 10) / 10)

function rdp(points, tolerance) {
  if (points.length < 4) return points
  const keep = new Array(points.length).fill(false)
  keep[0] = keep[points.length - 1] = true
  const stack = [[0, points.length - 1]]
  while (stack.length) {
    const [a, b] = stack.pop()
    const [ax, ay] = points[a], [bx, by] = points[b]
    const dx = bx - ax, dy = by - ay, length = Math.hypot(dx, dy) || 1e-9
    let worst = 0, at = -1
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs(dy * (points[i][0] - ax) - dx * (points[i][1] - ay)) / length
      if (d > worst) { worst = d; at = i }
    }
    if (worst > tolerance && at > 0) { keep[at] = true; stack.push([a, at], [at, b]) }
  }
  return points.filter((_, i) => keep[i])
}

function windowMap({ lon0, lon1, lat0, lat1, width, tolerance, minArea = 3 }) {
  const k = Math.cos(((lat0 + lat1) / 2) * Math.PI / 180)
  const S = width / ((lon1 - lon0) * k)
  const project = ([lon, lat]) => [(lon - lon0) * k * S, (lat1 - lat) * S]
  const countries = []
  for (const f of geo.features) {
    let d = ''
    for (const poly of polys(f.geometry)) {
      const ring = poly[0]
      const lons = ring.map(p => p[0]), lats = ring.map(p => p[1])
      if (Math.max(...lons) < lon0 || Math.min(...lons) > lon1 || Math.max(...lats) < lat0 || Math.min(...lats) > lat1) continue
      let r = rdp(ring.slice(0, -1).map(project), tolerance)
      if (r.length < 3 || area(r) < minArea) continue
      d += 'M' + r.map(([x, y]) => `${f1(x)} ${f1(y)}`).join('L') + 'Z'
    }
    if (d) countries.push({ id: f.properties.ADM0_A3, name: f.properties.NAME, d })
  }
  const center = ([lon, lat]) => project([lon, lat]).map(Math.round)
  return { w: width, h: Math.ceil((lat1 - lat0) * S), countries, center: Object.fromEntries(
    Object.entries({ COL: [-74.0, 4.6], MWI: [34.2, -13.2], ETH: [39.5, 8.5], KEN: [37.8, 0.6], SOM: [46, 4.5], BRA: [-52, -11], IND: [79, 22], MLI: [-3.5, 17], NGA: [8.2, 9.6], SYR: [38.5, 35], YEM: [47.5, 15.8], BFA: [-1.7, 12.3], CMR: [12.7, 5.8] })
      .map(([id, p]) => [id, center(p)])) }
}

const evidence = windowMap({ lon0: -82, lon1: 98, lat0: -36, lat1: 40, width: 560, tolerance: 0.35 })
const horn = windowMap({ lon0: -17, lon1: 58, lat0: -3, lat1: 39, width: 560, tolerance: 0.3, minArea: 2 })
const header = `/* Generated by scripts/build-world.mjs. Do not edit by hand.
   Natural Earth 1:50m admin-0 countries (public domain). The study countries come from the RAE workbook. */
`
await writeFile(new URL('../data/world-maps.js', import.meta.url), `${header}export const worldMaps = ${JSON.stringify({ evidence, horn })}\n`)
