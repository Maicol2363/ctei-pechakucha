// Builds data/study-outlines.js: country outlines for slide 2 (Brazil; Kenya, Somalia, Ethiopia).
// Inputs: geoBoundaries gbOpen ADM0 simplified GeoJSON files (build 9469f09), passed as --bra --ken --som --eth.
//   Brazil: IBGE, CC BY 3.0 IGO. Kenya: RCMRD, public domain. Somalia: UNDP/OCHA, CC BY 3.0 IGO. Ethiopia: Open Africa, ODbL 1.0.
import { readFile, writeFile } from 'node:fs/promises'

const arg = name => { const i = process.argv.indexOf(`--${name}`); return i > 0 ? process.argv[i + 1] : undefined }
const load = async name => JSON.parse(await readFile(arg(name), 'utf8')).features[0].geometry
const polys = g => g.type === 'Polygon' ? [g.coordinates] : g.coordinates

function rdp(points, tolerance) {
  if (points.length < 3) return points
  const keep = new Array(points.length).fill(false)
  keep[0] = keep[points.length - 1] = true
  const stack = [[0, points.length - 1]]
  while (stack.length) {
    const [a, b] = stack.pop()
    const [ax, ay] = points[a], [bx, by] = points[b]
    const dx = bx - ax, dy = by - ay, length = Math.hypot(dx, dy) || 1e-9
    let worst = 0, at = -1
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs(dy * (points[i][0] - ax) - dx * (points[i][1] - ay)) / length
      if (d > worst) { worst = d; at = i }
    }
    if (worst > tolerance && at > 0) { keep[at] = true; stack.push([a, at], [at, b]) }
  }
  return points.filter((_, i) => keep[i])
}
const area = ring => Math.abs(ring.reduce((s, p, i) => { const q = ring[(i + 1) % ring.length]; return s + p[0] * q[1] - q[0] * p[1] }, 0)) / 2
const f1 = n => String(Math.round(n * 10) / 10)

function group(geometries, width, tolerance) {
  const all = geometries.flatMap(g => polys(g).flatMap(p => p[0]))
  const lon0 = Math.min(...all.map(p => p[0])), lon1 = Math.max(...all.map(p => p[0]))
  const lat0 = Math.min(...all.map(p => p[1])), lat1 = Math.max(...all.map(p => p[1]))
  const k = Math.cos(((lat0 + lat1) / 2) * Math.PI / 180)
  const S = width / ((lon1 - lon0) * k)
  const project = ([lon, lat]) => [(lon - lon0) * k * S, (lat1 - lat) * S]
  const paths = geometries.map(g => {
    let d = ''
    for (const poly of polys(g)) {
      let ring = poly[0].map(project)
      if (ring.length > 1 && ring[0][0] === ring.at(-1)[0] && ring[0][1] === ring.at(-1)[1]) ring = ring.slice(0, -1)
      ring = rdp(ring, tolerance)
      if (ring.length < 3 || area(ring) < 6) continue
      d += 'M' + ring.map(([x, y]) => `${f1(x)} ${f1(y)}`).join('L') + 'Z'
    }
    return d
  })
  return { w: width, h: Math.ceil((lat1 - lat0) * S), paths }
}

const brazil = group([await load('bra')], 400, 0.9)
const horn = group([await load('ken'), await load('som'), await load('eth')], 400, 0.7)
const header = `/* Generated by scripts/build-outlines.mjs. Do not edit by hand.
   geoBoundaries gbOpen ADM0: Brazil (IBGE, CC BY 3.0 IGO), Kenya (RCMRD, public domain),
   Somalia (UNDP and OCHA Somalia, CC BY 3.0 IGO), Ethiopia (Open Africa, ODbL 1.0). */
`
await writeFile(new URL('../data/study-outlines.js', import.meta.url), `${header}export const outlines = ${JSON.stringify({
  brazil: { w: brazil.w, h: brazil.h, d: brazil.paths[0] },
  horn: { w: horn.w, h: horn.h, kenya: horn.paths[0], somalia: horn.paths[1], ethiopia: horn.paths[2] },
})}\n`)
