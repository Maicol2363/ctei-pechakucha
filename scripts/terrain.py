"""Download AWS Terrain Tiles (Terrarium) around Cundinamarca and write contour lines as SVG paths.

Output uses the same projection as data/cundinamarca-map.js so contours register with the municipal outlines.
"""
import io, json, os, math, re, sys, time, urllib.request
import numpy as np
from PIL import Image
import contourpy

SLIDEV = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(SLIDEV, 'data', 'terrain-contours.js')
js = open(os.path.join(SLIDEV, 'data', 'cundinamarca-map.js'), encoding='utf8').read()
data = json.loads(js[js.index('{'):js.rindex('}') + 1])
P = data['proj']
W, H = data['w'], data['h']
Z = 9
pad = 0.04
lon0, lon1, lat0, lat1 = P['lon0'] - pad, P['lon1'] + pad, P['lat0'] - pad, P['lat1'] + pad


def tile(lon, lat):
    n = 2 ** Z
    x = (lon + 180) / 360 * n
    y = (1 - math.asinh(math.tan(math.radians(lat))) / math.pi) / 2 * n
    return x, y


x0, y1 = tile(lon0, lat0)
x1, y0 = tile(lon1, lat1)
tx0, tx1, ty0, ty1 = int(x0), int(x1), int(y0), int(y1)
print('tiles', tx0, tx1, ty0, ty1)
mosaic = np.zeros(((ty1 - ty0 + 1) * 256, (tx1 - tx0 + 1) * 256), dtype=np.float32)
for ty in range(ty0, ty1 + 1):
    for tx in range(tx0, tx1 + 1):
        url = f'https://s3.amazonaws.com/elevation-tiles-prod/terrarium/{Z}/{tx}/{ty}.png'
        raw = urllib.request.urlopen(urllib.request.Request(url, headers={'User-Agent': 'course-presentation-research/1.0'})).read()
        im = np.asarray(Image.open(io.BytesIO(raw)).convert('RGB'), dtype=np.float32)
        elev = im[:, :, 0] * 256 + im[:, :, 1] + im[:, :, 2] / 256 - 32768
        mosaic[(ty - ty0) * 256:(ty - ty0 + 1) * 256, (tx - tx0) * 256:(tx - tx0 + 1) * 256] = elev
        time.sleep(0.15)
print('elev range', mosaic.min(), mosaic.max())

# smooth a little so contours read as clean lines rather than pixel noise
from scipy.ndimage import gaussian_filter
mosaic = gaussian_filter(mosaic, 2.2)

# pixel -> lon/lat -> the deck's projection
n = 2 ** Z
def px_to_svg(ix, iy):
    gx = tx0 + ix / 256
    gy = ty0 + iy / 256
    lon = gx / n * 360 - 180
    lat = math.degrees(math.atan(math.sinh(math.pi * (1 - 2 * gy / n))))
    return (lon - P['lon0']) * P['k'] * P['S'], (P['lat1'] - lat) * P['S']


def rdp(points, tol):
    if len(points) < 4:
        return points
    keep = [False] * len(points)
    keep[0] = keep[-1] = True
    stack = [(0, len(points) - 1)]
    while stack:
        a, b = stack.pop()
        ax, ay = points[a]; bx, by = points[b]
        dx, dy = bx - ax, by - ay
        length = math.hypot(dx, dy) or 1e-9
        worst, at = 0, -1
        for i in range(a + 1, b):
            d = abs(dy * (points[i][0] - ax) - dx * (points[i][1] - ay)) / length
            if d > worst:
                worst, at = d, i
        if worst > tol and at > 0:
            keep[at] = True
            stack += [(a, at), (at, b)]
    return [p for p, k in zip(points, keep) if k]


levels = list(range(300, 4000, 150))
gen = contourpy.contour_generator(z=mosaic, name='serial', line_type=contourpy.LineType.Separate)
out = {'w': W, 'h': H, 'minor': '', 'major': ''}
total = 0
for lvl in levels:
    major = lvl % 600 == 0
    d = ''
    for line in gen.lines(lvl):
        if len(line) < 35:
            continue
        pts = [px_to_svg(x, y) for x, y in line]
        pts = rdp(pts, 0.9)
        if len(pts) < 4:
            continue
        d += 'M' + 'L'.join(f'{x:.1f} {y:.1f}' for x, y in pts)
        total += len(pts)
    out['major' if major else 'minor'] += d
print('points', total, 'minor', len(out['minor']), 'major', len(out['major']))
header = '/* Generated by scripts/terrain.py (see Slidev_Visual_Reference.md). Do not edit by hand.\n   Contours from AWS Terrain Tiles (Terrarium, zoom 9), which draw on NASADEM, SRTM and other open elevation sources.\n   Registered to the municipal outlines in cundinamarca-map.js. */\n'
open(OUT, 'w', encoding='utf8').write(header + 'export const terrain = ' + json.dumps(out) + '\n')
print('wrote', OUT)
